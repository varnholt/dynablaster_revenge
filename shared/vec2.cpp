#include "vec2.h"

#include <cmath>


//-----------------------------------------------------------------------------
Vec2::Vec2()
   : mX(0.0f),
     mY(0.0f)
{
}


//-----------------------------------------------------------------------------
Vec2::Vec2(float x, float y)
   : mX(x),
     mY(y)
{
}


//-----------------------------------------------------------------------------
float Vec2::x() const
{
   return mX;
}


//-----------------------------------------------------------------------------
float Vec2::y() const
{
   return mY;
}


//-----------------------------------------------------------------------------
void Vec2::setX(float x)
{
   mX = x;
}


//-----------------------------------------------------------------------------
void Vec2::setY(float y)
{
   mY = y;
}


//-----------------------------------------------------------------------------
float Vec2::length() const
{
   return std::sqrt(mX * mX + mY * mY);
}


//-----------------------------------------------------------------------------
Vec2 Vec2::operator-(const Vec2& other) const
{
   return Vec2(mX - other.mX, mY - other.mY);
}
